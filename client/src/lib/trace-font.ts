// trace-font — the site's display face is not a font, it is a beam path.
//
// A hand-authored single-stroke glyph set (engineering-lettering register, on
// mono proportions): each glyph is one or more polylines in a 14-unit cap
// height grid (y down, baseline at 14). Headlines render these as SVG paths
// that DRAW via stroke-dashoffset when the beam visits them, which fuses
// typography and charts into one drawing system. Uppercase + digits + the few
// symbols headlines actually use; TracedText upper-cases its input.

export interface TraceGlyph {
  /** advance width in grid units (gap added by the renderer) */
  w: number;
  /** polylines: arrays of [x, y] points */
  strokes: number[][][];
}

