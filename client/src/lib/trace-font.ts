/** Fallback for unknown characters: an empty box advance */
const FALLBACK: TraceGlyph = { w: 8, strokes: [[[0, 0], [8, 0], [8, 14], [0, 14], [0, 0]]] };

export function traceGlyph(ch: string): TraceGlyph {
  return G[ch] ?? G[ch.toUpperCase()] ?? FALLBACK;
}

export interface TracedGlyphPath {
  /** SVG path data, already offset to its pen position */
  d: string;
  /** total polyline length in grid units (for dash timing weights) */
  len: number;
  ch: string;
}

export interface TracedLine {
  glyphs: TracedGlyphPath[];
  /** total advance width in grid units */
  width: number;
}

function strokeLen(pts: number[][]): number {
  let l = 0;
  for (let i = 1; i < pts.length; i++) {
    const dx = pts[i][0] - pts[i - 1][0];
    const dy = pts[i][1] - pts[i - 1][1];
    l += Math.hypot(dx, dy);
  }
  return l;
}

/** Lay out a line of text as per-glyph SVG paths in grid units. */
export function layoutTraceText(text: string): TracedLine {
  const glyphs: TracedGlyphPath[] = [];
  let x = 0;
  for (const raw of text) {
    const ch = raw === " " ? " " : raw;
    const g = traceGlyph(ch.toUpperCase());
    if (g.strokes.length > 0) {
      let d = "";
      let len = 0;
      for (const s of g.strokes) {
        d += `M${(x + s[0][0]).toFixed(2)} ${s[0][1].toFixed(2)}`;
        for (let i = 1; i < s.length; i++) {
          d += `L${(x + s[i][0]).toFixed(2)} ${s[i][1].toFixed(2)}`;
        }
        len += strokeLen(s);
      }
      glyphs.push({ d, len, ch });
    }
    x += g.w + TRACE_GAP;
  }
  return { glyphs, width: Math.max(0, x - TRACE_GAP) };
}
