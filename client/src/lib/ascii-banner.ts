// ascii-banner — the wordmark in the oldest register the site speaks: text.
//
// Figlet-small glyphs, composed programmatically so the rows can't drift out
// of alignment. Full alphabet + digits: the "/" terminal boot line, the
// footer plate, and every section headline (ascii-heading) render from this
// one set.

